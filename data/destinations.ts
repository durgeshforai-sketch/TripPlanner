const BY_ID = new Map(DESTINATIONS.map((d) => [d.id, d]));

export function getDestination(id: string): Destination | undefined {
  return BY_ID.get(id);
}

/** Loose name match used to resolve a typed destination to the catalog. */
export function findDestinationByName(name: string): Destination | undefined {
  const needle = name.trim().toLowerCase();
  if (!needle) return undefined;
  return (
    DESTINATIONS.find((d) => d.name.toLowerCase() === needle || d.city.toLowerCase() === needle) ??
    DESTINATIONS.find(
      (d) =>
        d.name.toLowerCase().includes(needle) ||
        needle.includes(d.name.toLowerCase()) ||
        d.city.toLowerCase().includes(needle),
    )
  );
}
